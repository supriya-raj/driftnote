-- Initial schema (docs/ARCHITECTURE.md, section 5.2). Migrations are forward-only.

CREATE TABLE notes (
  note_id        TEXT    PRIMARY KEY,        -- random 21-char ID, generated by the browser
  state          BLOB    NOT NULL,           -- whole note, compacted into one Yjs update
  schema_version INTEGER NOT NULL,
  created_at     INTEGER NOT NULL,
  updated_at     INTEGER NOT NULL
);

CREATE TABLE tokens (
  token_id   INTEGER PRIMARY KEY,                       -- short, non-secret label
  note_id    TEXT    NOT NULL REFERENCES notes (note_id),
  token_hash BLOB    NOT NULL UNIQUE,                   -- SHA-256; plaintext never stored
  role       TEXT    NOT NULL CHECK (role IN ('owner', 'edit', 'view')),
  created_at INTEGER NOT NULL,
  revoked_at INTEGER                                    -- set on revoke; row kept
);
CREATE INDEX tokens_by_note ON tokens (note_id);

CREATE TABLE tombstones (
  note_id    TEXT    PRIMARY KEY,                       -- deleted note; refuses future syncs
  deleted_at INTEGER NOT NULL
);

CREATE TABLE snapshots (
  snapshot_id INTEGER PRIMARY KEY,
  note_id     TEXT    NOT NULL REFERENCES notes (note_id),
  created_at  INTEGER NOT NULL,
  kind        TEXT    NOT NULL CHECK (kind IN ('auto', 'named', 'pre-restore')),
  name        TEXT,                                     -- only for 'named'
  state       BLOB    NOT NULL,
  size_bytes  INTEGER NOT NULL
);
CREATE INDEX snapshots_by_note_time ON snapshots (note_id, created_at DESC);
